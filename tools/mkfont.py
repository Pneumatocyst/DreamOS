#!/usr/bin/env python3
"""Turn the Inter fonts in assets/fonts/ into anti-aliased bitmap fonts the kernel can draw.

    python3 tools/mkfont.py > kernel/gfx/uifont_data.c

The kernel has no font engine (no FreeType, no floats), so we do the hard part here,
once, on the build machine: render every printable ASCII character at a few fixed
sizes, and store each one as a little block of coverage values (0 = empty, 255 = solid).
gfx_utext() then blends the text colour into the surface using those values, which
is what makes the edges smooth.

Needs Pillow (pip install pillow). The output is committed, so a normal build
doesn't need Python at all; re-run this only when changing sizes or fonts.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, '..', 'assets', 'fonts')

ASCII = ''.join(chr(c) for c in range(32, 127))
DIGITS = ' 0123456789:'

# (C name, font file, pixel size, characters)
SIZES = [
    ('font_ui',      'Inter-Regular.otf',      14, ASCII),
    ('font_bold',    'Inter-SemiBold.otf',     14, ASCII),
    ('font_small',   'Inter-Regular.otf',      12, ASCII),
    ('font_title',   'Inter-SemiBold.otf',     20, ASCII),
    ('font_big',     'InterDisplay-Light.otf', 34, ASCII),
    ('font_display', 'InterDisplay-Light.otf', 96, DIGITS),
]


def render(name, file, size, chars, out):
    font = ImageFont.truetype(os.path.join(FONTS, file), size)
    ascent, descent = font.getmetrics()
    line_h = ascent + descent
    pad = size
    bitmap = bytearray()
    glyphs = {}
    for ch in chars:
        img = Image.new('L', (size * 3 + pad * 2, line_h + pad * 2), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor='ls')
        box = img.getbbox()
        adv = round(font.getlength(ch) * 16)          # advance in 1/16 px
        if not box:
            glyphs[ch] = (0, 0, 0, 0, adv, 0)
            continue
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        glyphs[ch] = (x1 - x0, y1 - y0, x0 - pad, y0 - pad, adv, len(bitmap))
        bitmap += crop.tobytes()

    out.append(f'static const uint8_t {name}_bits[{max(len(bitmap), 1)}] = {{')
    for i in range(0, len(bitmap), 24):
        out.append('    ' + ','.join(str(b) for b in bitmap[i:i + 24]) + ',')
    out.append('};')
    out.append(f'static const struct uiglyph {name}_glyphs[95] = {{')
    for c in range(32, 127):
        g = glyphs.get(chr(c))
        if g is None:
            out.append('    { 0, 0, 0, 0, 0, 0 },')
        else:
            out.append('    {{ {}, {}, {}, {}, {}, {} }},  /* {} */'.format(*g, repr(chr(c)).replace('*/', '* /')))
    out.append('};')
    out.append(f'const struct uifont {name} = {{ {line_h}, {ascent}, {name}_glyphs, {name}_bits }};')
    out.append('')


def main():
    out = ['/* GENERATED by tools/mkfont.py from the Inter typeface (assets/fonts, SIL OFL 1.1).',
           '   Do not edit by hand: change tools/mkfont.py and re-run it. */',
           '#include "gfx/gfx.h"', '']
    for args in SIZES:
        render(*args, out)
    sys.stdout.write('\n'.join(out))


if __name__ == '__main__':
    main()
